  // Bullet points, not a bare number wall — one small card per judge, its
  // own verdict/severity breakdown as a short list, critical/moderate
  // highlighted. Judge names are relabeled to plain English (no raw
  // judge_name strings) per this project's dashboard-clarity convention.
  function renderJudgeOutputRollup(rollup) {
    const byJudge = (rollup && rollup.by_judge) || {};
    const judgeNames = Object.keys(JUDGEOUTPUT_JUDGE_LABELS).filter((name) => byJudge[name] && byJudge[name].length);
    if (!judgeNames.length) {
      return `<p class="empty-state">No automated judging data yet — generate a brief to produce some.</p>`;
    }
    const cards = judgeNames
      .map((name) => {
        const rows = byJudge[name];
        const total = rows.reduce((sum, r) => sum + r.n, 0);
        const items = rows
          .map((r) => {
            const isCritical = r.severity === "critical";
            const isModerate = r.severity === "moderate";
            const label = r.severity && r.severity !== "none" ? r.severity : r.verdict;
            const icon = isCritical
              ? `<i data-lucide="alert-triangle" class="goldset-severity-icon is-critical"></i>`
              : isModerate
              ? `<i data-lucide="alert-triangle" class="goldset-severity-icon is-moderate"></i>`
              : "";
            return `<li class="${isCritical ? "judgeoutput-rollup-critical" : ""}">${r.n} ${escapeHtml(label)} ${icon}</li>`;
          })
          .join("");
        const problemStat = JUDGEOUTPUT_PROBLEM_STAT[name];
        let problemBadge = "";
        if (problemStat && total > 0) {
          const problemCount = rows.filter(problemStat.match).reduce((sum, r) => sum + r.n, 0);
          const pct = Math.round((problemCount / total) * 100);
          problemBadge = ` <span class="judgeoutput-flag-badge ${problemStat.badgeClass}">${pct}% ${escapeHtml(problemStat.label)}</span>`;
        }
        return `
          <div class="judgeoutput-rollup-card">
            <div class="judgeoutput-rollup-card-title">${escapeHtml(JUDGEOUTPUT_JUDGE_LABELS[name])} <span class="judgeoutput-rollup-card-total">(${total})</span>${problemBadge}</div>
            <ul class="judgeoutput-rollup-list">${items}</ul>
          </div>
        `;
      })
      .join("");
    return `
      <div class="goldset-section-heading">Last ${rollup.days} Days</div>
      <div class="judgeoutput-rollup-grid">${cards}</div>
    `;
  }

  function renderJudgeOutputRunList() {
    const listEl = document.getElementById("judgeoutput-run-list");
    const runs = state.judgeOutput.runs;
    if (!runs.length) {
      listEl.innerHTML = `<p class="empty-state">No automated judging runs yet.</p>`;
      return;
    }
    listEl.innerHTML = runs
      .map((r) => {
        const selected = r.run_id === state.judgeOutput.selectedRunId ? " selected" : "";
        const kindLabel = r.kind === "generate_brief" ? "Full run" : "Bookends-only run";
        const flagBits = [];
        if (r.critical_count > 0) flagBits.push(`<span class="judgeoutput-flag-badge is-critical">${r.critical_count} critical</span>`);
        if (r.moderate_count > 0) flagBits.push(`<span class="judgeoutput-flag-badge is-moderate">${r.moderate_count} moderate</span>`);
        const relBits = [];
        if (r.hit_count > 0) relBits.push(`<span class="judgeoutput-flag-badge is-hit">${r.hit_count} hit${r.hit_count === 1 ? "" : "s"}</span>`);
        if (r.miss_count > 0) relBits.push(`<span class="judgeoutput-flag-badge is-miss">${r.miss_count} miss${r.miss_count === 1 ? "" : "es"}</span>`);
        return `
          <div class="goldset-run-card${selected}" data-run-id="${r.run_id}">
            <div class="goldset-run-card-label">${escapeHtml(r.email || "Unknown user")}</div>
            <div class="goldset-run-card-meta">${kindLabel} — ${new Date(r.started_at).toLocaleString()}</div>
            ${flagBits.length ? `<div class="goldset-run-card-meta">${flagBits.join(" ")}</div>` : ""}
            ${relBits.length ? `<div class="goldset-run-card-meta">Relevance: ${relBits.join(" ")}</div>` : ""}
          </div>
        `;
      })
      .join("");
  }

