  async function saveNewHarnessUser() {
    const email = document.getElementById("input-new-user-email").value.trim();
    const locationName = document.getElementById("input-new-user-location").value.trim();
    const scheduledTime = document.getElementById("input-new-user-time").value || "07:00";
    if (!email || !locationName) {
      alert("Email and location are required.");
      return;
    }

    const existing = state.harness.users.find((u) => u.email.toLowerCase() === email.toLowerCase());
    if (
      existing &&
      !confirm(
        "A user with this email already exists — this will update their location/schedule and add these topics without removing existing ones. Continue?",
      )
    ) {
      return;
    }

    const chosenTopicNames = Array.from(
      document.querySelectorAll("#add-user-topic-checkboxes input[type=checkbox]:checked"),
    ).map((cb) => cb.value);
    const customTopicNames = document
      .getElementById("input-new-user-custom-topics")
      .value.split(",")
      .map((s) => s.trim())
      .filter(Boolean);

    const btn = document.getElementById("btn-save-new-user");
    btn.disabled = true;
    try {
      const res = await fetch("/api/harness/users", {
        method: "POST",
        headers: getHeaders(),
        body: JSON.stringify({
          email,
          location_name: locationName,
          scheduled_time: scheduledTime,
          chosen_topic_names: chosenTopicNames,
          custom_topic_names: customTopicNames,
        }),
      });
      const data = await res.json();
      assertStepOk(res, data);

      const idx = state.harness.users.findIndex((u) => u.id === data.id);
      if (idx >= 0) state.harness.users[idx] = data;
      else state.harness.users.push(data);

      const select = document.getElementById("select-harness-user");
      select.innerHTML =
        `<option value="">Select a user…</option>` +
        state.harness.users
          .map((u) => `<option value="${u.id}">${u.email} — ${u.location_name}</option>`)
          .join("");
      select.value = data.id;
      renderHarnessUserDetail(data.id);

      closeAddUserModal();
    } catch (e) {
      console.error("Failed to create harness user:", e);
      alert("Error creating user: " + e.message);
    } finally {
      btn.disabled = false;
    }
  }

