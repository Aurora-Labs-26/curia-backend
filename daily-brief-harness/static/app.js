  // Same bullet-point/severity-icon language as Gold Set's faithfulness
  // table (renderGoldSetJudgesView), rebuilt here rather than shared
  // because that function assumes a single frozen run with gold labels to
  // compare against — this one never has gold labels, and only ever covers
  // the 5-judge automated set (see eval_judges_service.AUTOMATED_JUDGE_SETS),
  // never the full 8. Pool identity ("Non-Local"/"Local") is named once per
  // section heading, never repeated per row.
  function renderJudgeOutputDetail(items, runMeta) {
    const byJudge = {};
    items.forEach((o) => {
      (byJudge[o.judge_name] = byJudge[o.judge_name] || []).push(o);
    });

    const kindLabel = runMeta.kind === "generate_brief" ? "Full run" : "Bookends-only run";
    const chosenTopics = (runMeta.chosen_topics || []).join(", ") || "none";
    const customTopics = (runMeta.custom_topics || []).join(", ") || "none";
    const header = `
      <div class="goldset-section-heading">${escapeHtml(runMeta.email || "Unknown user")} — ${kindLabel}</div>
      <p class="pool-item-meta">${runMeta.started_at ? new Date(runMeta.started_at).toLocaleString() : ""} — ${escapeHtml(runMeta.location_name || "")}</p>
      <p class="pool-item-meta">Topics: ${escapeHtml(chosenTopics)} — Custom: ${escapeHtml(customTopics)}</p>
    `;

    // Relevance and Top Pick/Order Ranking render as 3-column tables
    // (Article/Check | Verdict | Reasoning) — easier to scan a specific
    // column across many rows than a bulleted "X — Y — Z" line. Faithfulness
    // below stays bulleted on purpose: claims are variable-length and don't
    // tabulate cleanly the way a single verdict+reasoning pair does.
    const relevancePool = (isLocal) => {
      const rows = (byJudge.relevance || []).filter((o) => o.is_local === isLocal).sort((a, b) => (a.rank ?? 0) - (b.rank ?? 0));
      if (!rows.length) return "";
      const rowsHtml = rows
        .map(
          (o) => `
            <tr>
              <td>${escapeHtml(o.title || o.url)}</td>
              <td>${
                o.verdict === "hit"
                  ? `Hit <i data-lucide="check" class="goldset-match-icon is-match"></i>`
                  : `Miss <i data-lucide="x" class="goldset-match-icon is-differ"></i>`
              }</td>
              <td>${escapeHtml(o.reasoning || "")}</td>
            </tr>
          `,
        )
        .join("");
      return `
        <div class="judgeoutput-subheading">${isLocal ? "Local" : "Non-Local"}</div>
        <div class="table-container">
          <table class="judgeoutput-table">
            <thead><tr><th>Article</th><th>Verdict</th><th>Reasoning</th></tr></thead>
            <tbody>${rowsHtml}</tbody>
          </table>
        </div>
      `;
    };
    const nonLocalRelevance = relevancePool(false);
    const localRelevance = relevancePool(true);
    const relevanceBlock = nonLocalRelevance || localRelevance
      ? `<div class="goldset-section-heading">Relevance</div>${nonLocalRelevance}${localRelevance}`
      : "";

    const orderRows = [
      ...(byJudge.order_correctness || []).map((o) => ({ ...o, label: "Top pick" })),
      ...(byJudge.order_ranking || []).map((o) => ({ ...o, label: "Order (ranks 2-N)" })),
    ];
    const orderBlock = orderRows.length
      ? `
        <div class="goldset-section-heading">Top Pick &amp; Order Ranking</div>
        <div class="table-container">
          <table class="judgeoutput-table">
            <thead><tr><th>Check</th><th>Verdict</th><th>Reasoning</th></tr></thead>
            <tbody>${orderRows
              .map(
                (o) => `
                  <tr>
                    <td>${o.is_local ? "Local" : "Non-local"} ${escapeHtml(o.label)}</td>
                    <td>${o.verdict === "agree" ? "Agrees with the pipeline" : "Disagrees"}</td>
                    <td>${escapeHtml(o.reasoning || "")}</td>
                  </tr>
                `,
              )
              .join("")}</tbody>
          </table>
        </div>
      `
      : "";

    // Each segment gets its own subheading (name + verdict) and, if it has
    // flagged claims, its own 2-column table — "Statement from Transcript"
    // paired with "Reasoning" instead of the two mashed into one
    // bullet with an em dash between them.
    const SEGMENT_ORDER = { intro: 0, lead: 1, standard: 2, local: 3, outro: 4 };
    const capitalizeSeg = (s) => (s ? s.charAt(0).toUpperCase() + s.slice(1) : "");
    const faithfulnessBlock = (judgeName, heading) => {
      const rows = (byJudge[judgeName] || []).sort(
        (a, b) =>
          (SEGMENT_ORDER[a.segment_type] ?? 9) - (SEGMENT_ORDER[b.segment_type] ?? 9) ||
          (a.rank ?? 0) - (b.rank ?? 0) ||
          (a.attempt_number ?? 1) - (b.attempt_number ?? 1),
      );
      if (!rows.length) return "";
      // A segment only ever shows more than one row here when
      // faithfulness_regen_service.py actually retried it (a flag on
      // attempt 1, resolved or not on a later one) — the common case is
      // exactly one row per segment_type, so the "(attempt N)" suffix below
      // only appears when there's something worth showing it for.
      const attemptCounts = {};
      rows.forEach((o) => { attemptCounts[o.segment_type] = (attemptCounts[o.segment_type] || 0) + 1; });
      const segmentsHtml = rows
        .map((o) => {
          const claims = (o.detail || {}).claims || [];
          let verdictLabel;
          if (o.severity === "critical") verdictLabel = `Critical <i data-lucide="alert-triangle" class="goldset-severity-icon is-critical"></i>`;
          else if (o.severity === "moderate") verdictLabel = `Moderate <i data-lucide="alert-triangle" class="goldset-severity-icon is-moderate"></i>`;
          else verdictLabel = "Clean";
          const claimsTable = claims.length
            ? `
              <div class="table-container">
                <table class="judgeoutput-claims-table">
                  <thead><tr><th>Statement from Transcript</th><th>Reasoning</th></tr></thead>
                  <tbody>${claims
                    .map((c) => `<tr><td>${escapeHtml(c.text)}</td><td>${escapeHtml(c.explanation)}</td></tr>`)
                    .join("")}</tbody>
                </table>
              </div>
            `
            : "";
          const attemptSuffix = attemptCounts[o.segment_type] > 1 ? ` (attempt ${o.attempt_number || 1})` : "";
          return `<div class="judgeoutput-subheading">${escapeHtml(capitalizeSeg(o.segment_type))}${attemptSuffix} — ${verdictLabel}</div>${claimsTable}`;
        })
        .join("");
      return `<div class="goldset-section-heading">${heading}</div>${segmentsHtml}`;
    };

    return `
      ${header}
      ${relevanceBlock}
      ${orderBlock}
      ${faithfulnessBlock("faithfulness_article", "Article Fact Faithfulness")}
      ${faithfulnessBlock("faithfulness_bookend", "Bookend/User Faithfulness")}
    `;
  }

