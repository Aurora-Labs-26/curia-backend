  // Self-contained: uses direct getElementById lookups rather than an
  // `elements` cache keyed to fixed step cards.

  function setMultiUserCardStatus(cardId, status, badgeText = null) {
    const card = document.getElementById(cardId);
    const ind = card.querySelector(".status-indicator");
    const badge = card.querySelector(".metric-badge");

    card.classList.remove("running", "success", "error", "active");
    ind.className = "status-indicator";

    if (status === "running") {
      card.classList.add("running");
      ind.classList.add("running");
      ind.textContent = "Running...";
    } else if (status === "success") {
      card.classList.add("success");
      ind.classList.add("success");
      ind.textContent = "Success";
    } else if (status === "error") {
      card.classList.add("error");
      ind.classList.add("error");
      ind.textContent = "Error";
    } else {
      card.classList.add("active");
      ind.classList.add("idle");
      ind.textContent = "Idle";
    }
    if (badgeText && badge) badge.textContent = badgeText;
  }

  function cacheBadge(cacheHit) {
    return `<span class="cache-badge ${cacheHit ? "hit" : "miss"}">${cacheHit ? "cache hit" : "cache miss"}</span>`;
  }

  async function loadHarnessUsers() {
    const select = document.getElementById("select-harness-user");
    if (!select) return; // tab markup not present (shouldn't happen, defensive only)
    try {
      const res = await fetch("/api/harness/users");
      const data = await res.json();
      state.harness.users = data.users || [];

      if (state.harness.users.length === 0) {
        select.innerHTML = `<option value="">No users yet — click + Add User above</option>`;
        return;
      }

      select.innerHTML =
        `<option value="">Select a user…</option>` +
        state.harness.users
          .map((u) => `<option value="${u.id}">${u.email} — ${u.location_name}</option>`)
          .join("");
    } catch (e) {
      console.error("Failed to load harness users:", e);
      select.innerHTML = `<option value="">Failed to load users</option>`;
    }
  }

