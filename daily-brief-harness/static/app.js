  // M3: LLM judge verdicts for the selected profile, cross-referenced
  // client-side against the gold labels/scripts already loaded in `d` (see
  // app/services/eval_judges_service.py — the API deliberately returns raw
  // judge_outputs rows rather than duplicating this join server-side).
  function renderGoldSetJudgesView(d) {
    const runId = state.goldSet.selectedRunId;
    const outputs = state.goldSet.judgeOutputsRunId === runId ? state.goldSet.judgeOutputs : null;
    const report = state.goldSet.judgeReport;
    const running = state.goldSet.judgesRunning;

    // report.relevance/order_correctness carry a per_profile breakdown keyed
    // by profile_label — this profile's own row is what's shown. Rendered
    // unconditionally (kappaCell falls back to "n/a") so the kappa table and
    // the Run Judges button always share one compact row, instead of the
    // button alone occupying a full-width block above everything else.
    const relevanceHere = report && report.relevance.per_profile[d.profile_label];
    const orderHere = report && report.order_correctness.per_profile[d.profile_label];
    const orderRankingHere = report && report.order_ranking.per_profile[d.profile_label];
    const kappaCell = (entry) => (entry && entry.kappa != null ? entry.kappa.toFixed(2) : "n/a");

    const topRow = `
      <div class="goldset-judges-toprow">
        <div class="goldset-kappa-block">
          <div class="goldset-section-heading">LLM v/s Human Agreement (Kappa Values)</div>
          <div class="table-container goldset-kappa-table">
            <table>
              <thead><tr><th>Judge</th><th>Agreement (kappa)</th></tr></thead>
              <tbody>
                <tr><td>Relevance</td><td>${kappaCell(relevanceHere)}</td></tr>
                <tr><td>Top pick</td><td>${kappaCell(orderHere)}</td></tr>
                <tr><td>Order ranking (#2-N)</td><td>${kappaCell(orderRankingHere)}</td></tr>
              </tbody>
            </table>
          </div>
        </div>
        <button class="primary-btn goldset-run-judges-btn" id="btn-run-judges" ${running ? "disabled" : ""}>
          <i data-lucide="gavel"></i> ${running ? "Running Judges…" : "Run Judges"}
        </button>
      </div>
    `;

    if (outputs === null) {
      return (
        topRow +
        `<p class="empty-state">${
          running
            ? "Judges are running — this can take a minute or two…"
            : "No judge results yet for this profile. Click “Run Judges”."
        }</p>`
      );
    }

    const allCandidates = [...d.non_local, ...d.local];
    // Judges run against the full uncapped pool, not just the gold view's
    // default-capped candidate list — prefer each row's own resolved title
    // (see eval_judges_service.list_judge_outputs) before falling back to
    // the capped candidate list, then the bare url as a last resort.
    const titleFor = (o) => {
      const url = typeof o === "string" ? o : o.url;
      if (typeof o === "object" && o.title) return o.title;
      const c = allCandidates.find((x) => x.url === url);
      return c ? c.title : url || "";
    };
    const goldLabelByUrl = {};
    allCandidates.forEach((c) => {
      goldLabelByUrl[c.url] = c.label;
    });

    const byJudge = {};
    outputs.forEach((o) => {
      (byJudge[o.judge_name] = byJudge[o.judge_name] || []).push(o);
    });

    // Real broadcast/segment order, not API insertion order — the model's
    // own JSON response order has nothing to do with how these articles/
    // segments were actually ranked or aired. Mirrors eval_gold_service
    // .get_labeling_view's SEGMENT_ORDER convention.
    const SEGMENT_ORDER = { intro: 0, lead: 1, standard: 2, local: 3, outro: 4 };
    const capitalizeSeg = (s) => (s ? s.charAt(0).toUpperCase() + s.slice(1) : "");

    // --- Hit/Miss Choice Comparison — one table per pool (was one table
    // with a "Non-local #3" style prefix baked into every row; the pool
    // identity is now the table's own header instead). Only labeled rows
    // show by default — on a 50+ candidate non-local pool the unlabeled
    // majority was pure noise — with a small "Show more" to reveal the rest.
    const buildHitMissTable = (isLocal, poolKey, headingSuffix) => {
      const rows = (byJudge.relevance || [])
        .filter((o) => o.is_local === isLocal)
        .sort((a, b) => (a.rank ?? 0) - (b.rank ?? 0));
      const built = rows.map((o) => {
        const gold = goldLabelByUrl[o.url];
        const labeled = gold != null;
        // No human label at all (outside what's actually been labeled) is
        // NOT the same as the judge disagreeing — "—" rather than a false
        // cross for rows with nothing to compare against.
        const matchIcon = !labeled
          ? "—"
          : o.verdict === gold
          ? `<i data-lucide="check" class="goldset-match-icon is-match"></i>`
          : `<i data-lucide="x" class="goldset-match-icon is-differ"></i>`;
        const rowHtml = `
          <tr>
            <td>#${o.rank ?? "?"} — ${escapeHtml(titleFor(o))}</td>
            <td>${escapeHtml(o.verdict)}</td>
            <td>${labeled ? escapeHtml(gold) : "—"}</td>
            <td>${matchIcon}</td>
            <td>${escapeHtml(o.reasoning || "")}</td>
          </tr>
        `;
        return { labeled, rowHtml };
      });
      const labeledRows = built.filter((r) => r.labeled).map((r) => r.rowHtml);
      const unlabeledRows = built.filter((r) => !r.labeled).map((r) => r.rowHtml);
      const expanded = state.goldSet.expandedHitMiss[poolKey];
      const extraHtml = unlabeledRows.length
        ? `
          <tbody class="goldset-extra-rows${expanded ? "" : " collapsed"}">
            ${unlabeledRows.join("")}
          </tbody>
          <tfoot>
            <tr>
              <td colspan="5">
                <button class="goldset-show-more-btn" data-pool="${poolKey}">
                  ${expanded ? "Show less" : `Show ${unlabeledRows.length} more`}
                </button>
              </td>
            </tr>
          </tfoot>
        `
        : "";
      const bodyHtml =
        labeledRows.join("") || (unlabeledRows.length ? "" : `<tr><td colspan="5">No relevance judge output yet.</td></tr>`);
      return `
        <div class="table-container">
          <table class="goldset-hitmiss-table">
            <thead><tr><th>Article (${headingSuffix})</th><th>LLM label</th><th>Human label</th><th>Match</th><th>Reasoning</th></tr></thead>
            <tbody>${bodyHtml}</tbody>
            ${extraHtml}
          </table>
        </div>
      `;
    };
    const hitMissHtml = `
      <div class="goldset-section-heading">Hit/Miss Choice Comparison</div>
      ${buildHitMissTable(false, "non_local", "Non-Local")}
      ${buildHitMissTable(true, "local", "Local")}
    `;

    // Two independent checks per pool now: "Top pick" (is #1 right against
    // the whole pool?) and "Order ranking" (are ranks 2-N in defensible
    // relative order?) — same judge call, two logged rows (judge_name
    // order_correctness / order_ranking), shown as two rows per pool here.
    const orderRows = [
      ...(byJudge.order_correctness || []).map((o) => ({ ...o, checkLabel: "Top pick" })),
      ...(byJudge.order_ranking || []).map((o) => ({ ...o, checkLabel: "Order ranking (#2-N)" })),
    ]
      .sort((a, b) => (a.is_local ? 1 : 0) - (b.is_local ? 1 : 0) || a.checkLabel.localeCompare(b.checkLabel))
      .map(
        (o) => `
        <tr>
          <td>${o.is_local ? "Local" : "Non-local"}</td>
          <td>${escapeHtml(o.checkLabel)}</td>
          <td>${escapeHtml(o.verdict)}</td>
          <td>${escapeHtml(o.reasoning || "")}</td>
        </tr>
      `
      )
      .join("");

    // --- Faithfulness (article + bookend) — the only spot-check judge with
    // a real, decidable per-segment verdict. No article titles here (the
    // segment TYPE is what matters — a wire-editor spot-check reads by
    // position, not headline); no separate "Judge" column (every row here
    // is a faithfulness check, so it'd be a constant); severity is an icon
    // instead of a bare parenthetical; each flagged claim is its own bullet
    // instead of one run-on sentence with inline [severity] tags.
    const faithfulnessRows = ["faithfulness_article", "faithfulness_bookend"]
      .flatMap((name) => (byJudge[name] || []).map((o) => ({ name, o })))
      .sort((a, b) => {
        const ka = [SEGMENT_ORDER[a.o.segment_type] ?? 9, a.o.rank ?? 0];
        const kb = [SEGMENT_ORDER[b.o.segment_type] ?? 9, b.o.rank ?? 0];
        return ka[0] - kb[0] || ka[1] - kb[1];
      })
      .map(({ name, o }) => {
        const claims = (o.detail || {}).claims || [];
        const reasoningHtml = claims.length
          ? `<ul class="goldset-claims-list">${claims
              .map((c) => `<li>${escapeHtml(c.text)} — ${escapeHtml(c.explanation)}</li>`)
              .join("")}</ul>`
          : "";
        const noSource = name === "faithfulness_article" && (o.detail || {}).source_available === false;
        let verdictHtml;
        if (o.severity === "critical") {
          verdictHtml = `Critical <i data-lucide="alert-triangle" class="goldset-severity-icon is-critical"></i>`;
        } else if (o.severity === "moderate") {
          verdictHtml = `Moderate <i data-lucide="alert-triangle" class="goldset-severity-icon is-moderate"></i>`;
        } else {
          verdictHtml = "Clean";
        }
        if (noSource) verdictHtml += ` <span class="goldset-no-source-badge">— no source fetched</span>`;
        return `
          <tr>
            <td>${escapeHtml(capitalizeSeg(o.segment_type))}</td>
            <td>${verdictHtml}</td>
            <td>${reasoningHtml}</td>
          </tr>
        `;
      })
      .join("");

    // --- Tone/flow + brief coherence — kept as their own small section
    // rather than folded into Faithfulness (a genuinely different question:
    // does this READ well, not is it factually true) or silently dropped.
    const explanationForToneCoherence = (name, o) => {
      const detail = o.detail || {};
      if (name === "tone_flow_pairwise") {
        const ab = detail.call_generated_first || {};
        const ba = detail.call_golden_first || {};
        return `Generated-first: ${ab.reasoning || "n/a"} | Golden-first: ${ba.reasoning || "n/a"}`;
      }
      if (name === "brief_coherence") {
        const parts = [];
        if (detail.weakest_transition) parts.push(`Weakest transition: ${detail.weakest_transition}`);
        if (detail.reasoning) parts.push(detail.reasoning);
        return parts.join(" — ");
      }
      return o.reasoning || "";
    };
    const toneCoherenceRows = ["tone_flow_pairwise", "brief_coherence"]
      .flatMap((name) => (byJudge[name] || []).map((o) => ({ name, o })))
      .sort((a, b) => {
        const ka = a.name === "brief_coherence" ? [5, 0] : [SEGMENT_ORDER[a.o.segment_type] ?? 9, a.o.rank ?? 0];
        const kb = b.name === "brief_coherence" ? [5, 0] : [SEGMENT_ORDER[b.o.segment_type] ?? 9, b.o.rank ?? 0];
        return ka[0] - kb[0] || ka[1] - kb[1];
      })
      .map(({ name, o }) => {
        const check = name === "tone_flow_pairwise" ? "Tone/Flow" : "Coherence";
        const item = name === "brief_coherence" ? "Whole brief" : capitalizeSeg(o.segment_type);
        const verdict = name === "brief_coherence" ? `${escapeHtml(o.verdict)}/5` : escapeHtml(o.verdict);
        return `
          <tr>
            <td>${check}</td>
            <td>${item}</td>
            <td>${verdict}</td>
            <td>${escapeHtml(explanationForToneCoherence(name, o))}</td>
          </tr>
        `;
      })
      .join("");

    return `
      ${topRow}
      ${hitMissHtml}
      <div class="goldset-section-heading">Order correctness</div>
      <div class="table-container">
        <table>
          <thead><tr><th>Pool</th><th>Check</th><th>Verdict</th><th>Reasoning</th></tr></thead>
          <tbody>${orderRows || `<tr><td colspan="4">No order-correctness judge output yet.</td></tr>`}</tbody>
        </table>
      </div>
      <div class="goldset-section-heading">Faithfulness (spot-check — no gold data for this yet)</div>
      <div class="table-container">
        <table>
          <thead><tr><th>Faithfulness Judge</th><th>Verdict</th><th>Reasoning</th></tr></thead>
          <tbody>${faithfulnessRows || `<tr><td colspan="3">No output yet.</td></tr>`}</tbody>
        </table>
      </div>
      <div class="goldset-section-heading">Tone/Flow &amp; Coherence (spot-check — no gold data for these yet)</div>
      <div class="table-container">
        <table>
          <thead><tr><th>Check</th><th>Item</th><th>Verdict</th><th>Reasoning</th></tr></thead>
          <tbody>${toneCoherenceRows || `<tr><td colspan="4">No output yet.</td></tr>`}</tbody>
        </table>
      </div>
    `;
  }

  async function loadGoldSetJudgeData(runId) {
    if (!runId) return;
    try {
      const [resultsRes, reportRes] = await Promise.all([
        fetch(`/api/eval/judges/results/${runId}`),
        fetch(`/api/eval/judges/validation-report`),
      ]);
      const resultsData = await resultsRes.json();
      assertStepOk(resultsRes, resultsData);
      const reportData = await reportRes.json();
      assertStepOk(reportRes, reportData);
      state.goldSet.judgeOutputs = resultsData.items || [];
      state.goldSet.judgeOutputsRunId = runId;
      state.goldSet.judgeReport = reportData;
      if (state.goldSet.selectedRunId === runId && state.goldSet.activeSubTab === "judges") {
        renderGoldSetDetail();
      }
    } catch (e) {
      console.error("Failed to load judge data:", e);
    }
  }

  async function runJudgesForSelectedProfile() {
    const runId = state.goldSet.selectedRunId;
    if (!runId || state.goldSet.judgesRunning) return;
    state.goldSet.judgesRunning = true;
    renderGoldSetDetail();
    try {
      const res = await fetch(`/api/eval/judges/run/${runId}`, { method: "POST", headers: getHeaders() });
      const data = await res.json();
      assertStepOk(res, data);
      await loadGoldSetJudgeData(runId);
    } catch (e) {
      console.error("Failed to run judges:", e);
      alert("Error running judges: " + e.message);
    } finally {
      state.goldSet.judgesRunning = false;
      renderGoldSetDetail();
    }
  }

  async function saveGoldLabel(url, label) {
    const runId = state.goldSet.selectedRunId;
    const d = state.goldSet.detail;
    if (!runId || !url || !d) return;
    try {
      const res = await fetch(`/api/eval/gold/runs/${runId}/labels`, {
        method: "POST",
        headers: getHeaders(),
        body: JSON.stringify({ url, label }),
      });
      const data = await res.json();
      assertStepOk(res, data);
      // Update local state directly instead of re-fetching the whole run —
      // avoids a network round trip and keeps the scroll position stable.
      const candidate = [...d.non_local, ...d.local].find((c) => c.url === url);
      if (candidate) candidate.label = label;
      renderGoldSetDetail();
    } catch (e) {
      console.error("Failed to save gold label:", e);
      alert("Error saving label: " + e.message);
    }
  }

