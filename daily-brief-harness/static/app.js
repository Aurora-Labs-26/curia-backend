  // ---------------------------------------------------------
  function safeCreateIcons() {
    try {
      if (typeof lucide !== "undefined") {
        lucide.createIcons();
      } else {
        console.warn(
          "Lucide icons package not loaded yet. Skipping rendering.",
        );
      }
    } catch (e) {
      console.warn("Lucide icons failed to render:", e);
    }
  }

  async function init() {
    safeCreateIcons();

    // Load custom API key from localStorage if it exists
    const storedKey = localStorage.getItem("anthropic_api_key");
    if (storedKey) {
      elements.inputApiKey.value = storedKey;
    }

    // Check backend connection status
    await checkBackendStatus();

    // Load users + system topics for the Multi-User Cache tab
    await loadHarnessUsers();
    await loadHarnessTopics();

    // Register UI listeners
    setupListeners();
  }

  // Throws a descriptive error using the backend's `detail` field when a pipeline
  // step API call fails, instead of letting the failure surface as a generic or
  // misleading message (or a raw TypeError from accessing undefined `.parsed`).
  function assertStepOk(res, data) {
    if (!res.ok) {
      throw new Error(
        (data && data.detail) || `Request failed with status ${res.status}`,
      );
    }
  }

  // Generate request headers with dynamic custom API Key injection
  function getHeaders() {
    const headers = {
      "Content-Type": "application/json",
    };
    const storedKey = localStorage.getItem("anthropic_api_key");
    if (storedKey && storedKey.trim() !== "") {
      headers["X-Anthropic-API-Key"] = storedKey.trim();
    }
    return headers;
  }

  // Check health and Anthropic configuration status
  async function checkBackendStatus() {
    try {
      const res = await fetch("/api/status", {
        headers: getHeaders(),
      });
      const data = await res.json();

      const dot = elements.statusBadge.querySelector(".status-dot");
      dot.className = "status-dot"; // reset class

      if (data.status === "healthy") {
        dot.classList.add("active");
        if (data.anthropic_key_configured) {
          elements.statusText.textContent = `Claude API Online (${data.anthropic_model})`;
          elements.statusBadge.style.borderColor = "var(--border-muted)";
          dot.style.backgroundColor = "var(--accent-green)";
          dot.style.boxShadow = "0 0 8px var(--accent-green)";
        } else {
          elements.statusText.textContent =
            "Claude Simulated Mode (No API Key)";
          elements.statusBadge.style.borderColor = "var(--accent-violet)";
          dot.style.backgroundColor = "var(--accent-violet)";
          dot.style.boxShadow = "0 0 8px var(--accent-violet)";
        }
      }
    } catch (e) {
      console.error("Backend unreachable: ", e);
      elements.statusText.textContent = "Backend offline";
      const dot = elements.statusBadge.querySelector(".status-dot");
      dot.className = "status-dot";
    }
  }

  // Escapes text for safe interpolation into innerHTML templates — shared by
  // every render function across Multi-User Cache and Open Coding.
  function escapeHtml(str) {
    const div = document.createElement("div");
    div.textContent = str || "";
    return div.innerHTML;
  }

